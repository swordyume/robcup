from maix import camera, display, image, app, uart, err, pinmap
import time
import struct


# ============================================================
# 相机
# ============================================================
cam = camera.Camera(320, 240)
disp = display.Display()


# ============================================================
# UART
# ============================================================
pin_function = {
    "A29": "UART2_RX",
    "A28": "UART2_TX"
}

for pin, func in pin_function.items():
    err.check_raise(
        pinmap.set_pin_function(pin, func),
        f"Failed set pin {pin} function to {func}"
    )

serial_dev = uart.UART("/dev/ttyS2", 115200)


# ============================================================
# 红色 + 绿色阈值
# find_blobs 可以一次检测多个颜色
# ============================================================
thresholds = [
    [0, 80, 40, 80, 10, 80],       # 红色
    [50, 80, -15, 10, -30, 0]       # 蓝色
]


# ============================================================
# 视觉控制参数
# ============================================================
U0 = 320 / 2

ALPHA = 0.3
DEADBAND_U = 6
MAX_JUMP_PIXEL = 30

CONTROL_INTERVAL_S = 0.1
K_Y = 0.01

LOST_FRAME_THRESHOLD = 3


# ============================================================
# 状态变量
# ============================================================
last_u_filtered = U0
target_lost = True

lost_frame_count = 0
last_control_time = 0


# ============================================================
# UART移动控制
# ============================================================
def send_move(distance):

    packet = (
        bytes([0x1C, 0xAD]) +
        struct.pack("<f", distance) +
        bytes([0x28])
    )

    serial_dev.write(packet)


# ============================================================
# 主循环
# ============================================================
while not app.need_exit():

    img = cam.read()

    # --------------------------------------------------------
    # 一次检测红色和绿色
    # --------------------------------------------------------
    blobs = img.find_blobs(
        thresholds,
        area_threshold=1000,
        pixels_threshold=1000
    )


    # --------------------------------------------------------
    # 检测到目标
    # --------------------------------------------------------
    if len(blobs) > 0:

        # 多个色块时，选择面积最大的一个
        blob = max(
            blobs,
            key=lambda x: x.w() * x.h()
        )


        # ----------------------------------------------------
        # 计算色块中心
        # ----------------------------------------------------
        u_raw = blob.x() + blob.w() / 2
        v_raw = blob.y() + blob.h() / 2


        lost_frame_count = 0


        # ----------------------------------------------------
        # 第一次检测到目标
        # ----------------------------------------------------
        if target_lost:

            last_u_filtered = u_raw
            target_lost = False


        else:

            # ------------------------------------------------
            # 跳变剔除
            # ------------------------------------------------
            if abs(u_raw - last_u_filtered) <= MAX_JUMP_PIXEL:

                # ------------------------------------------------
                # 一阶低通滤波
                # ------------------------------------------------
                last_u_filtered = (
                    ALPHA * u_raw
                    + (1 - ALPHA) * last_u_filtered
                )


        # ----------------------------------------------------
        # 计算水平偏差
        # ----------------------------------------------------
        delta_u = last_u_filtered - U0


        # ----------------------------------------------------
        # 绘制色块
        # ----------------------------------------------------
        img.draw_rect(
            blob.x(),
            blob.y(),
            blob.w(),
            blob.h(),
            image.COLOR_GREEN
        )


        # ----------------------------------------------------
        # 控制发送
        # ----------------------------------------------------
        current_time = time.perf_counter()

        if (
            abs(delta_u) > DEADBAND_U
            and
            current_time - last_control_time >= CONTROL_INTERVAL_S
        ):

            move_y = K_Y * delta_u

            print(move_y)

            send_move(move_y)

            last_control_time = current_time


    # --------------------------------------------------------
    # 没检测到红色或绿色
    # --------------------------------------------------------
    else:

        lost_frame_count += 1

        if lost_frame_count >= LOST_FRAME_THRESHOLD:
            target_lost = True


    # --------------------------------------------------------
    # 显示
    # --------------------------------------------------------
    disp.show(img)
